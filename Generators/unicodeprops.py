#!/usr/bin/env python3
"""Generate Sources/Toolbox/unicode_props_gen.c: Unicode character properties.

Run from the repository root:

    python3 Generators/unicodeprops.py

For UCGetCharProperty (TextCommon.h): the general category, canonical
combining class and bidirectional category of every code point, as runs
in the numbering that interface gives them.  The data is Python's own
(the Unicode Character Database of its version), not Apple's.
"""
import os
import sys
import unicodedata

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "Sources", "Toolbox", "unicode_props_gen.c")

# kUCGenlCat... of TextCommon.h
GENERAL = {
    "Cn": 0, "Cc": 1, "Cf": 2, "Cs": 3, "Co": 4, "Mn": 5, "Mc": 6, "Me": 7, "Nd": 8, "Nl": 9, "No": 10,
    "Zs": 11, "Zl": 12, "Zp": 13, "Lu": 14, "Ll": 15, "Lt": 16, "Lm": 17, "Lo": 18, "Pc": 20, "Pd": 21,
    "Ps": 22, "Pe": 23, "Pi": 24, "Pf": 25, "Po": 26, "Sm": 28, "Sc": 29, "Sk": 30, "So": 31,
}
# kUCBidiCat...
BIDI = {
    "": 0, "L": 1, "R": 2, "EN": 3, "ES": 4, "ET": 5, "AN": 6, "CS": 7, "B": 8, "S": 9, "WS": 10, "ON": 11,
    "AL": 12, "LRE": 13, "RLE": 14, "LRO": 15, "RLO": 16, "PDF": 17, "NSM": 18, "BN": 19,
    # isolates are newer than the interface: neutrals
    "LRI": 11, "RLI": 11, "FSI": 11, "PDI": 11,
}


def runs(f):
    out = []
    start, cur = 0, f(0)
    for cp in range(1, 0x110000):
        v = f(cp)
        if v != cur:
            out.append((start, cur))
            start, cur = cp, v
    out.append((start, cur))
    return out


def main():
    props = [
        ("general", lambda cp: GENERAL[unicodedata.category(chr(cp))]),
        ("combining", lambda cp: unicodedata.combining(chr(cp))),
        ("bidi", lambda cp: BIDI[unicodedata.bidirectional(chr(cp))]),
    ]
    lines = ["/* Generated by Generators/unicodeprops.py (Unicode %s). Do not edit. */" % unicodedata.unidata_version,
             "#include <stdint.h>", "#include <stddef.h>", "",
             "typedef struct { uint32_t start; uint8_t value; } uc_run;", ""]
    for name, f in props:
        r = runs(f)
        lines.append("const uc_run uc_%s_runs[] = {" % name)
        row = []
        for s, v in r:
            row.append("{0x%X,%d}," % (s, v))
            if len(row) == 8:
                lines.append("    " + " ".join(row))
                row = []
        if row:
            lines.append("    " + " ".join(row))
        lines.append("};")
        lines.append("const size_t uc_%s_count = sizeof uc_%s_runs / sizeof uc_%s_runs[0];" % (name, name, name))
        lines.append("")
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote", OUT, file=sys.stderr)


main()
