"""QuickTime's component calls for PowerPC programs.

  uv run python Generators/qt_calls.py --scan <Universal Interfaces CIncludes>
      reads the interfaces' component call declarations (the calls whose
      68k form is _ComponentDispatch with a selector) and writes
      Generators/defs/qt_calls.tsv: name, selector, the sizes of the
      arguments after the instance (4 a long or pointer, 2 a short, 1 a
      Boolean or byte, passed as a word, f a float, which PowerPC code
      passes in a floating-point register), and the call's family.
  uv run python Generators/qt_calls.py
      writes Sources/Toolbox/qt_calls_gen.c from that table.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "Generators", "defs", "qt_calls.tsv")
OUT = os.path.join(ROOT, "Sources", "Toolbox", "qt_calls_gen.c")

HEADERS = ["Movies.h", "ImageCompression.h", "ImageCodec.h", "QuickTimeComponents.h", "MediaHandlers.h",
           "QuickTimeMusic.h", "QTStreamingComponents.h", "QTSMovie.h", "IsochronousDataHandler.h"]

ONE = {"Boolean", "Byte", "UInt8", "SInt8", "char", "unsigned char", "signed char", "Style"}
TWO = {"short", "unsigned short", "SInt16", "UInt16", "OSErr", "ScriptCode", "ShortFixed", "LangCode",
       "RegionCode", "INTEGER", "CharParameter"}

# The component families: a call's is the longest of these its name starts
# with (the next letter a capital), and a component of ours takes the calls
# of the families it implements.
FAMILIES = ["CallComponent", "Clock", "Curve", "DataCodec", "DataH", "FlashMedia", "GraphicsExport",
            "GraphicsImageImport", "GraphicsImport", "IDH", "ImageCodec", "ImageTranscoder", "MC", "MIDIImport", "Media", "Media3D",
            "MovieExport", "MovieImport", "MovieMedia", "Music", "MusicMedia", "NA", "Preview", "QTMIDI",
            "QTPhoto", "QTSMedia", "QTSSourcer", "QTVideoOutput", "RTPMP", "RTPPB", "RTPRssm", "SC", "SG",
            "SpriteMedia", "TC", "TextExport", "TextMedia", "Tune", "Tweener", "VD", "VideoMedia", "XMLParse"]


def family(name):
    best = None
    for f in FAMILIES:
        if name.startswith(f) and (len(name) == len(f) or name[len(f)].isupper()) and \
                (best is None or len(f) > len(best)):
            best = f
    if best is None:
        raise SystemExit("no family for " + name)
    return best


DECL = re.compile(r"EXTERN_API(?:_C)?\(\s*([^;{}()]*?)\s*\)\s*\n\s*(\w+)\(\s*([^;{}]*?)\)\s*"
                  r"FIVEWORDINLINE\(0x2F3C,\s*0x([0-9A-Fa-f]{4}),\s*0x([0-9A-Fa-f]{4}),\s*0x7000,\s*0xA82A\)\s*;")


def arg_size(a):
    a = " ".join(a.replace("const ", "").split())
    if "*" in a or "[" in a:
        return 4
    ty = " ".join(a.split()[:-1])
    if ty in ("QTFloatSingle", "float"):
        return "f"
    if ty in ONE:
        return 1
    if ty in TWO:
        return 2
    return 4


def scan(inc):
    rows, bad = {}, []
    for h in HEADERS:
        text = open(os.path.join(inc, h), encoding="latin1").read()
        for m in DECL.finditer(text):
            _, name, args, size, sel = m.groups()
            args = [a.strip() for a in args.split(",") if a.strip() and a.strip() != "void"]
            sizes = "".join(str(arg_size(a)) for a in args[1:])
            total = sum(2 if c == "1" else 4 if c == "f" else int(c) for c in sizes)
            if total != int(size, 16):
                bad.append((name, sizes, int(size, 16)))
            if name not in rows:
                rows[name] = (int(sel, 16), sizes)
    for b in bad:
        print("size mismatch:", *b, file=sys.stderr)
    with open(TSV, "w") as f:
        f.write("# QuickTime component calls: name, selector, argument sizes, family (qt_calls.py)\n")
        for name in sorted(rows):
            sel, sizes = rows[name]
            f.write(f"{name}\t0x{sel:04X}\t{sizes or '-'}\t{family(name)}\n")
    print(f"{len(rows)} calls, {len(bad)} mismatched", file=sys.stderr)


def gen():
    rows = []
    for line in open(TSV):
        if line.startswith("#") or not line.strip():
            continue
        name, sel, sizes, fam = line.rstrip("\n").split("\t")
        rows.append((name, int(sel, 16), "" if sizes == "-" else sizes, fam))
    rows.sort()
    out = ["/* Generated by Generators/qt_calls.py from Generators/defs/qt_calls.tsv. Do not edit. */\n",
           '#include "qt_calls.h"\n\n']
    for i in range(len(rows)):
        out.append(f"static void q{i}(ppc_cpu *c) {{ qt_call_ppc(c, {i}); }}\n")
    out.append("\nconst qt_call_info qt_calls[] = {\n")
    for i, (name, sel, sizes, fam) in enumerate(rows):
        out.append(f'    {{ "{name}", 0x{sel:04X}, "{sizes}", "{fam}", q{i} }},\n')
    out.append("};\nconst unsigned qt_call_count = sizeof qt_calls / sizeof qt_calls[0];\n")
    with open(OUT, "w") as f:
        f.write("".join(out))
    print(f"{len(rows)} calls", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--scan":
        scan(sys.argv[2])
    else:
        gen()
