#!/usr/bin/env python3
"""Generate C sources from the Multiversal interface definitions.

Run from the repository root:

    uv run --with pyyaml python Generators/gen.py

Outputs (all committed, so a normal build never needs Python):

    Sources/CCore/include/lowmem_gen.h      low-memory global addresses
    Sources/CCore/lowmem_gen.c              low-memory name table
    Sources/CCore/include/structs_gen.h     guest struct offsets, sizes, accessors
    Sources/Toolbox/include/tb_protos_gen.h prototypes for implemented tb_* routines
    Sources/Toolbox/traps_gen.c             trap names, signatures, generated glue

A Toolbox routine is "implemented" when some Sources/Toolbox/*.c file defines a
function named tb_<Name>.  Its C signature is derived from the definition, so a
mismatch between the definition and the implementation is a compile error.
"""

import glob
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DEFS = os.path.join(ROOT, "Defs", "multiversal", "defs")
OUT_CCORE = os.path.join(ROOT, "Sources", "CCore")
OUT_TOOLBOX = os.path.join(ROOT, "Sources", "Toolbox")

HEADER = "/* Generated by Generators/gen.py from Defs/multiversal. Do not edit. */\n"

# --------------------------------------------------------------------------
# Loading

typedefs = {}
structs = {}      # name -> dict(kind='struct'|'union', members=[...], size=?)
commons = {}
funptrs = set()
lowmems = []
functions = []
dispatchers = {}
enum_types = set()
constants = {}

BASE = {
    "int8_t": (1, True), "uint8_t": (1, False), "char": (1, True),
    "unsigned char": (1, False), "signed char": (1, True),
    "int16_t": (2, True), "uint16_t": (2, False), "short": (2, True),
    "unsigned short": (2, False),
    "int32_t": (4, True), "uint32_t": (4, False), "long": (4, True),
    "unsigned long": (4, False), "int": (4, True), "unsigned": (4, False),
    "unsigned int": (4, False),
    "bool": (1, False), "void": (0, False),
    "int64_t": (8, True), "uint64_t": (8, False),
    "float": (4, True), "double": (8, True),
}


def load():
    local = os.path.join(os.path.dirname(os.path.abspath(__file__)), "defs")
    for path in sorted(glob.glob(os.path.join(DEFS, "*.yaml"))) + sorted(glob.glob(os.path.join(local, "*.yaml"))):
        with open(path) as f:
            items = yaml.safe_load(f) or []
        for item in items:
            for kind, v in item.items():
                if not isinstance(v, dict):
                    continue
                if kind == "typedef":
                    typedefs[v["name"]] = v["type"]
                elif kind in ("struct", "union"):
                    # A struct may appear twice: once with members, once with
                    # only its declared size.  Merge the two.
                    s = structs.setdefault(v["name"], dict(kind=kind, members=[], size=None))
                    if v.get("members"):
                        s["members"] = v["members"]
                        s["kind"] = kind
                    if v.get("size") is not None:
                        s["size"] = v["size"]
                elif kind == "common":
                    commons[v["name"]] = v.get("members") or []
                elif kind == "funptr":
                    funptrs.add(v["name"])
                elif kind == "lowmem":
                    lowmems.append(v)
                elif kind == "function":
                    # A later definition (Generators/defs) replaces one of
                    # the same name and selector.
                    functions[:] = [f for f in functions
                                    if not (f.get("name") == v.get("name") and f.get("selector") == v.get("selector"))]
                    functions.append(v)
                elif kind == "dispatcher":
                    dispatchers[v["name"]] = v
                elif kind == "enum":
                    if v.get("name"):
                        enum_types.add(v["name"])
                    for ev in v.get("values") or []:
                        if isinstance(ev, dict) and "value" in ev:
                            constants[ev["name"]] = ev["value"]


# --------------------------------------------------------------------------
# Type layout (mac68k alignment: 1-byte types byte-aligned, everything else
# word-aligned, aggregate sizes padded to even)

class TypeInfo:
    def __init__(self, size, align, signed=False, scalar=True, ptr=False, struct=None):
        self.size, self.align, self.signed = size, align, signed
        self.scalar, self.ptr, self.struct = scalar, ptr, struct


def clean(t):
    t = t.strip()
    t = re.sub(r"\bconst\b", "", t)
    t = re.sub(r"\bvolatile\b", "", t)
    t = re.sub(r"\bstruct\b", "", t)
    return " ".join(t.split())


layout_cache = {}


def type_info(t, depth=0):
    if depth > 40:
        raise ValueError("typedef loop at " + t)
    t = clean(t)
    m = re.match(r"^(.*)\[(\w+)\]$", t)
    if m:
        elem = type_info(m.group(1), depth + 1)
        n = constants.get(m.group(2), m.group(2))
        n = int(n, 0) if isinstance(n, str) else int(n)
        return TypeInfo(elem.size * n, elem.align, scalar=False)
    if t.endswith("*") or t in funptrs or t.endswith("UPP") or t == "ProcPtr":
        return TypeInfo(4, 2, ptr=True)
    if t in BASE:
        size, signed = BASE[t]
        return TypeInfo(size, 1 if size <= 1 else 2, signed)
    if t in typedefs:
        return type_info(typedefs[t], depth + 1)
    if t in structs:
        size, align = struct_layout(t)[1:]
        return TypeInfo(size, align, scalar=False, struct=t)
    if t in enum_types:
        return TypeInfo(2, 2, True)
    raise KeyError(t)


def member_list(members):
    out = []
    for m in members:
        if "common" in m:
            out.extend(member_list(commons[m["common"]]))
        else:
            out.append(m)
    return out


def struct_layout(name):
    """Return (fields, size, align); fields = [(name, offset, TypeInfo)]."""
    if name in layout_cache:
        return layout_cache[name]
    s = structs[name]
    fields, size, align = layout_members(s["kind"], member_list(s["members"]))
    layout_cache[name] = (fields, size, align)
    return layout_cache[name]


def layout_members(kind, members):
    fields = []
    off = 0
    maxsize = 0
    align = 1
    for m in members:
        if "union" in m or "struct" in m:
            sub_kind = "union" if "union" in m else "struct"
            sub_fields, sub_size, sub_align = layout_members(sub_kind, member_list(m[sub_kind]))
            ti = TypeInfo(sub_size, sub_align, scalar=False)
            nested = sub_fields
        else:
            ti = type_info(m["type"])
            nested = None
        align = max(align, ti.align)
        if kind == "struct":
            if ti.align > 1 and off % 2:
                off += 1
            fields.append((m["name"], off, ti))
            if nested:
                for (n2, o2, t2) in nested:
                    fields.append((m["name"] + "_" + n2, off + o2, t2))
            off += ti.size
        else:
            fields.append((m["name"], 0, ti))
            if nested:
                for (n2, o2, t2) in nested:
                    fields.append((m["name"] + "_" + n2, o2, t2))
            maxsize = max(maxsize, ti.size)
    size = off if kind == "struct" else maxsize
    if align > 1 and size % 2:
        size += 1
    return fields, size, align


