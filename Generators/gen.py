# Traps and glue

def implemented_names():
    names = set()
    for path in glob.glob(os.path.join(OUT_TOOLBOX, "*.c")):
        if path.endswith("_gen.c"):
            continue
        with open(path) as f:
            for line in f:
                m = re.match(r"^[A-Za-z_][\w \*]*?\btb_(\w+)\s*\(", line)
                if m:
                    names.add(m.group(1))
    return names


def trap_num(v):
    t = v.get("trap")
    if t is None:
        return None
    return int(t, 0) if isinstance(t, str) else int(t)


def arg_class(a):
    """Classify an argument: ('stack', TypeInfo) or ('reg', regspec, TypeInfo)."""
    ti = type_info(a["type"])
    if not ti.scalar and not ti.ptr:
        # Aggregates: arrays and big records travel by address; records of
        # 4 bytes or fewer travel by value.
        if ti.struct and ti.size <= 4:
            pass
        else:
            ti = TypeInfo(4, 2, ptr=True)
    if "register" in a:
        return ("reg", a["register"], ti)
    return ("stack", None, ti)


def stack_slot(ti):
    return 2 if ti.size <= 2 else 4


def ctype_for(ti):
    if ti.ptr:
        return "gaddr"
    if ti.struct and ti.size <= 4:
        return "uint32_t" if ti.size == 4 else "uint16_t"
    return {1: "uint8_t" if not ti.signed else "int8_t",
            2: "uint16_t" if not ti.signed else "int16_t",
            4: "uint32_t" if not ti.signed else "int32_t"}[ti.size]


def signature(fn):
    """Analyse a function definition. Returns dict or raises."""
    args = []
    regs = False
    for i, a in enumerate(fn.get("args") or []):
        cls = arg_class(a)
        if cls[0] == "reg":
            regs = True
        args.append((a.get("name") or f"arg{i}", cls))
    ret = fn.get("return")
    rti = None
    if ret and clean(ret) != "void":
        rti = type_info(ret)
        if not rti.scalar and not rti.ptr:
            if rti.struct and rti.size <= 4:
                pass
            else:
                raise ValueError("aggregate return")
    retreg = fn.get("returnreg")
    conv = "reg" if (regs or retreg) else "stack"
    if conv == "reg" and any(c[0] == "stack" for _, c in args):
        raise ValueError("mixed register/stack arguments")
    argbytes = sum(stack_slot(c[2]) for _, c in args if c[0] == "stack")
    retbytes = 0 if (rti is None or conv == "reg") else stack_slot(rti)
    return dict(conv=conv, args=args, rti=rti, retreg=retreg,
                argbytes=argbytes, retbytes=retbytes,
                memerr="ReturnMemErr<D0>" in str(fn.get("executor_extras", "")))


REGS = {"D0": "c->d[0]", "D1": "c->d[1]", "D2": "c->d[2]", "A0": "c->a[0]",
        "A1": "c->a[1]", "A2": "c->a[2]"}


def c_params(sig):
    params = []
    for name, cls in sig["args"]:
        kind, reg, ti = cls
        if kind == "reg" and reg.startswith("TrapBit"):
            params.append(f"bool {name}")
        elif kind == "reg" and (reg.startswith("Out<") or reg.startswith("InOut<")):
            params.append(f"uint32_t *{name}")
        else:
            params.append(f"{ctype_for(ti)} {name}")
    return params


def c_return(sig):
    if sig["rti"] is None:
        return "void"
    if sig["retreg"] == "D0Minus1Boolean":
        return "bool"
    return ctype_for(sig["rti"])


TRAPBITS = {"SYSBIT": "0x400", "CLRBIT": "0x200"}


def gen_glue(name, sig):
    """Glue reading 68k arguments, calling tb_<name>, storing the result."""
    lines = [f"static void glue_{name}(cpu68k *c, uint16_t trapword)\n{{\n",
             "    (void)trapword;\n"]
    call_args = []
    if sig["conv"] == "c":
        # C (QuickDraw GX): the caller pushes the arguments last first, each
        # widened to a long, and pops them itself; the result is in D0 (and
        # A0 for a pointer, as either is where C compilers looked).
        for i, (name_, cls) in enumerate(sig["args"]):
            ct = ctype_for(cls[2])
            lines.append(f"    {ct} a_{name_} = ({ct})rd32(c->a[7] + {4 + 4 * i});\n")
        call_args = ["a_" + n for n, _ in sig["args"]]
        rt = c_return(sig)
        call = f"tb_{name}({', '.join(call_args)})"
        if rt == "void":
            lines.append(f"    {call};\n")
        else:
            lines.append(f"    {rt} r = {call};\n")
            lines.append("    c->d[0] = (uint32_t)r;\n")
            if sig["rti"].ptr:
                lines.append("    c->a[0] = (uint32_t)r;\n")
    elif sig["conv"] == "stack":
        lines.append("    uint32_t ret = cpu_pop32(c);\n")
        # Pascal pushes left to right, so the last argument is on top.
        for name_, cls in reversed(sig["args"]):
            ti = cls[2]
            ct = ctype_for(ti)
            if stack_slot(ti) == 4:
                lines.append(f"    {ct} a_{name_} = ({ct})cpu_pop32(c);\n")
            elif ti.size == 1:
                lines.append(f"    {ct} a_{name_} = ({ct})(cpu_pop16(c) >> 8);\n")
            else:
                lines.append(f"    {ct} a_{name_} = ({ct})cpu_pop16(c);\n")
        call_args = ["a_" + n for n, _ in sig["args"]]
        rt = c_return(sig)
        call = f"tb_{name}({', '.join(call_args)})"
        if rt == "void":
            lines.append(f"    {call};\n")
        else:
            lines.append(f"    {rt} r = {call};\n")
            ti = sig["rti"]
            if ti.size == 1:
                lines.append("    wr16(c->a[7], (uint16_t)((uint8_t)r << 8));\n")
            elif stack_slot(ti) == 2:
                lines.append("    wr16(c->a[7], (uint16_t)r);\n")
            else:
                lines.append("    wr32(c->a[7], (uint32_t)r);\n")
        lines.append("    cpu_push32(c, ret);\n")
    else:
        outs = []
        for name_, cls in sig["args"]:
            _, reg, ti = cls
            ct = ctype_for(ti)
            if reg.startswith("TrapBit"):
                bit = reg[len("TrapBit<"):-1]
                bit = TRAPBITS.get(bit, bit)
                lines.append(f"    bool a_{name_} = (trapword & {bit}) != 0;\n")
                call_args.append("a_" + name_)
            elif reg.startswith("Out<") or reg.startswith("InOut<"):
                r = reg[reg.index("<") + 1:-1]
                init = REGS[r] if reg.startswith("InOut") else "0"
                lines.append(f"    uint32_t a_{name_} = {init};\n")
                call_args.append("&a_" + name_)
                outs.append((r, "a_" + name_))
            elif reg == "D0LowWord":
                lines.append(f"    {ct} a_{name_} = ({ct})(c->d[0] & 0xFFFF);\n")
                call_args.append("a_" + name_)
            elif reg == "D0HighWord":
                lines.append(f"    {ct} a_{name_} = ({ct})(c->d[0] >> 16);\n")
                call_args.append("a_" + name_)
            else:
                lines.append(f"    {ct} a_{name_} = ({ct}){REGS[reg]};\n")
                call_args.append("a_" + name_)
        rt = c_return(sig)
        call = f"tb_{name}({', '.join(call_args)})"
        if rt == "void":
            lines.append(f"    {call};\n")
        else:
            lines.append(f"    {rt} r = {call};\n")
        for r, n_ in outs:
            lines.append(f"    {REGS[r]} = {n_};\n")
        rr = sig["retreg"]
        if rt != "void":
            if rr == "D0Minus1Boolean":
                lines.append("    c->d[0] = r ? 0 : 0xFFFFFFFFu;\n")
            elif rr in REGS:
                if sig["rti"].size == 2 and sig["rti"].signed:
                    lines.append(f"    {REGS[rr]} = (uint32_t)(int32_t)(int16_t)r;\n")
                else:
                    lines.append(f"    {REGS[rr]} = (uint32_t)r;\n")
            else:
                lines.append(f"    c->d[0] = (uint32_t)r;\n")
        if sig["memerr"]:
            lines.append("    c->d[0] = (uint32_t)(int32_t)(int16_t)rd16(LM_MemErr);\n")
    lines.append("}\n\n")
    return "".join(lines)


# ---------------------------------------------------------------------------
# PowerPC: InterfaceLib's exports, each a glue taking its arguments in the
# PowerPC calling convention (r3 to r10, then the caller's parameter area at
# 24(r1)), calling tb_<name> and returning the result in r3.

def ppc_variant_bits(variant, reg):
    """The value a trap-bit argument takes in a named variant (NewPtrClear, PBReadAsync)."""
    bit = reg[len("TrapBit<"):-1]
    if bit in ("SYSBIT",):
        return "Sys" in variant
    if bit in ("CLRBIT", "0x200"):
        return "Clear" in variant or "Imm" in variant
    if bit == "0x400":
        return "Async" in variant or ("Sys" in variant and "Sync" not in variant)
    return False


def gen_ppc_glue(name, fn, sig, variant):
    """Glue for one exported name (the function or one of its variants)."""
    if any(c[0] == "reg" and (c[1].startswith("Out<") or c[1].startswith("InOut<")) for _, c in sig["args"]):
        return None
    fixed = variant is not None
    cname = f"ppcglue_{variant or name}"
    lines = [f"static void {cname}(ppc_cpu *c)\n{{\n"]
    call_args = []
    # A struct result (NumVersion, Point) comes back through a pointer the
    # caller passes in r3; the arguments follow it.
    struct_result = ppc_struct_result(fn, sig)
    slot = 1 if struct_result else 0
    for name_, cls in sig["args"]:
        kind, reg, ti = cls
        if kind == "reg" and reg.startswith("TrapBit") and (fixed or not name.startswith("PB")):
            # A named variant sets its bits; otherwise only the PB calls
            # take the bit (async) as an argument, and the rest are the
            # plain call (PurgeSpace, MaxMem: the application heap).
            call_args.append("true" if fixed and ppc_variant_bits(variant, reg) else "false")
            continue
        ct = "bool" if (kind == "reg" and reg.startswith("TrapBit")) else ctype_for(ti)
        src = f"c->gpr[{3 + slot}]" if slot < 8 else f"rd32(c->gpr[1] + {24 + 4 * slot})"
        if ct == "bool":
            lines.append(f"    bool a_{name_} = {src} != 0;\n")
        else:
            lines.append(f"    {ct} a_{name_} = ({ct}){src};\n")
        call_args.append("a_" + name_)
        slot += 1
    rt = c_return(sig)
    call = f"tb_{name}({', '.join(call_args)})"
    # A parameter block call: ioResult set and an asynchronous call's
    # completion routine queued, as the 68k trap dispatcher does.
    pb_arg = next((n for n, c in sig["args"] if c[0] == "reg" and c[1] == "A0"), None)
    async_arg = next((n for n, c in sig["args"] if c[0] == "reg" and c[1] == "TrapBit<0x400>"), None)
    if name.startswith("PB") and pb_arg and async_arg and rt == "int16_t":
        if fixed:
            asy = "true" if ppc_variant_bits(variant, "TrapBit<0x400>") else "false"
        else:
            asy = "a_" + async_arg
        call = f"pb_call_done(a_{pb_arg}, {call}, {asy})"
    if rt == "void":
        lines.append(f"    {call};\n")
    elif struct_result:
        lines.append(f"    gaddr result = c->gpr[3];\n    {rt} r = {call};\n")
        lines.append(f"    ppc_struct_result(c, result, (uint32_t)r, {sig['rti'].size});\n")
    elif rt == "bool":
        lines.append(f"    c->gpr[3] = {call} ? 1 : 0;\n")
    else:
        ti = sig["rti"]
        if ti.signed and ti.size < 4:
            lines.append(f"    c->gpr[3] = (uint32_t)(int32_t)({rt}){call};\n")
        else:
            lines.append(f"    c->gpr[3] = (uint32_t){call};\n")
    lines.append("    c->pc = c->lr;\n}\n\n")
    return cname, "".join(lines)


REG_INDEX = {"D0": 0, "D1": 1, "D2": 2, "A0": 8, "A1": 9, "A2": 10}

# Results that are structs in C though the definitions call them longs; a
# PowerPC caller passes a pointer for them in r3.
PPC_STRUCT_RESULTS = {"NumVersion"}


def ppc_struct_result(fn, sig):
    ret = clean(fn.get("return") or "void")
    return sig["rti"] is not None and (sig["rti"].struct is not None or ret in PPC_STRUCT_RESULTS)


def selector_value(fn):
    sel = fn.get("selector")
    return int(sel, 0) if isinstance(sel, str) else int(sel)


def gen_ppc_trapcall(name, fn, sig, variant):
    """Glue for an export with no tb_ function to call: it runs the 68k trap
    itself (any patch on it included), the arguments pushed or in registers
    as the 68k interface has them."""
    for _, (kind, reg, ti) in sig["args"]:
        if ti.scalar and ti.size not in (1, 2, 4):
            return None
    if sig["rti"] is not None and sig["rti"].scalar and sig["rti"].size not in (1, 2, 4):
        return None
    disp = dispatchers.get(fn.get("dispatcher")) if fn.get("dispatcher") else None
    if fn.get("dispatcher"):
        if disp is None or fn.get("selector") is None:
            return None
        trap = trap_num(disp)
        loc = disp["selector-location"].rstrip("`")
        sel = selector_value(fn)
    else:
        trap = trap_num(fn)
        loc, sel = None, None
    if trap is None:
        return None
    if loc == "TrapBits":
        trap = (trap & ~0x0600) | ((sel & 3) << 9)
    # An OS trap that answers in A0 has bit 8 set, or the dispatcher would
    # put the caller's A0 back over the answer (PurgeSpace is $A162).
    answers_a0 = sig["retreg"] == "A0" or any(
        c[0] == "reg" and c[1] in ("Out<A0>", "InOut<A0>") for _, c in sig["args"])
    if not (trap & 0x0800) and answers_a0:
        trap |= 0x0100
    cname = f"ppctrap_{variant or name}"
    lines = [f"static void {cname}(ppc_cpu *c)\n{{\n", "    ppc_trap_begin();\n"]
    bits = []
    outs = []
    struct_result = ppc_struct_result(fn, sig)
    slot = 1 if struct_result else 0
    if sig["conv"] == "stack" and sig["retbytes"]:
        lines.append(f"    ppc_trap_push({sig['retbytes']}, 0);\n")
    if loc in ("D0W", "D0L") or (loc or "").startswith("D0<"):
        lines.append(f"    ppc_trap_set(0, 0x{sel & 0xFFFFFFFF:X}u);\n")
    for name_, (kind, reg, ti) in sig["args"]:
        if kind == "reg" and reg.startswith("TrapBit"):
            bit = reg[len("TrapBit<"):-1]
            bit = TRAPBITS.get(bit, bit)
            if variant is not None or not name.startswith("PB"):
                if variant is not None and ppc_variant_bits(variant, reg):
                    bits.append(f"{bit}")
                continue
            src = f"c->gpr[{3 + slot}]" if slot < 8 else f"rd32(c->gpr[1] + {24 + 4 * slot})"
            bits.append(f"({src} ? {bit} : 0)")
            slot += 1
            continue
        src = f"c->gpr[{3 + slot}]" if slot < 8 else f"rd32(c->gpr[1] + {24 + 4 * slot})"
        slot += 1
        if kind == "stack":
            size = 1 if ti.size == 1 and not ti.ptr else stack_slot(ti)
            lines.append(f"    ppc_trap_push({size}, {src});\n")
        elif reg.startswith("Out<") or reg.startswith("InOut<"):
            r = REG_INDEX[reg[reg.index("<") + 1:-1]]
            lines.append(f"    gaddr o_{name_} = {src};\n")
            if reg.startswith("InOut"):
                lines.append(f"    ppc_trap_set({r}, o_{name_} ? rd32(o_{name_}) : 0);\n")
            outs.append((r, "o_" + name_))
        elif reg == "D0LowWord":
            lines.append(f"    ppc_trap_set(0, (ppc_trap_get(0) & 0xFFFF0000u) | ({src} & 0xFFFF));\n")
        elif reg == "D0HighWord":
            lines.append(f"    ppc_trap_set(0, (ppc_trap_get(0) & 0xFFFF) | ({src} << 16));\n")
        else:
            v = src
            if ti.scalar and ti.signed and ti.size < 4:
                v = f"(uint32_t)(int32_t)(int{ti.size * 8}_t){src}"
            lines.append(f"    ppc_trap_set({REG_INDEX[reg]}, {v});\n")
    if loc in ("StackW", "StackWLookahead<0xFF>", "StackWMasked<0xFF>"):
        lines.append(f"    ppc_trap_push(2, 0x{sel & 0xFFFF:X});\n")
    elif loc == "StackL":
        lines.append(f"    ppc_trap_push(4, 0x{sel & 0xFFFFFFFF:X}u);\n")
    tw = f"0x{trap:04X}" + "".join(f" | {b}" for b in bits)
    lines.append(f"    ppc_trap((uint16_t)({tw}));\n")
    for r, o in outs:
        lines.append(f"    if ({o}) wr32({o}, ppc_trap_get({r}));\n")
    ti = sig["rti"]
    if ti is not None:
        if sig["conv"] == "stack":
            v = f"ppc_trap_result({1 if ti.size == 1 and not ti.ptr else stack_slot(ti)})"
        elif sig["retreg"] == "D0Minus1Boolean":
            v = "ppc_trap_get(0) == 0"
        else:
            v = f"ppc_trap_get({REG_INDEX.get(sig['retreg'] or 'D0', 0)})"
        if ti.scalar and ti.size < 4:
            t = f"int{ti.size * 8}_t" if ti.signed else f"uint{ti.size * 8}_t"
            v = f"(uint32_t)({'(int32_t)' if ti.signed else ''}({t})({v}))"
        lines.append(f"    uint32_t r = {v};\n")
    lines.append("    ppc_trap_end();\n")
    if ti is not None and struct_result:
        lines.append(f"    ppc_struct_result(c, c->gpr[3], r, {ti.size});\n")
    elif ti is not None:
        lines.append("    c->gpr[3] = r;\n")
    lines.append("    c->pc = c->lr;\n}\n\n")
    return cname, "".join(lines)


def gen_ppc_lowmem():
    """LMGetX / LMSetX for each low-memory global: scalars by value, records
    through a pointer, arrays (strings) by address."""
    out, table, seen = [], [], set()
    for v in lowmems:
        name = v["name"]
        if name in seen or not re.match(r"^[A-Z]", name):
            continue
        seen.add(name)
        addr = v["address"]
        addr = int(addr, 0) if isinstance(addr, str) else int(addr)
        try:
            ti = type_info(v["type"])
        except (KeyError, ValueError):
            continue
        get, set_ = f"ppclm_get_{name}", f"ppclm_set_{name}"
        if (ti.scalar or ti.ptr) and ti.size in (1, 2, 4):
            rd = {1: "rd8", 2: "rd16", 4: "rd32"}[ti.size]
            wr = {1: "wr8", 2: "wr16", 4: "wr32"}[ti.size]
            val = f"{rd}(0x{addr:X})"
            if ti.signed and ti.size < 4:
                val = f"(uint32_t)(int32_t)(int{ti.size * 8}_t){val}"
            out.append(f"static void {get}(ppc_cpu *c) {{ c->gpr[3] = {val}; c->pc = c->lr; }}\n")
            out.append(f"static void {set_}(ppc_cpu *c) {{ {wr}(0x{addr:X}, (uint{ti.size * 8}_t)c->gpr[3]); c->pc = c->lr; }}\n")
        elif ti.struct:
            out.append(f"static void {get}(ppc_cpu *c) {{ ppc_copy(c->gpr[3], 0x{addr:X}, {ti.size}); c->pc = c->lr; }}\n")
            out.append(f"static void {set_}(ppc_cpu *c) {{ ppc_copy(0x{addr:X}, c->gpr[3], {ti.size}); c->pc = c->lr; }}\n")
        elif not ti.scalar:
            out.append(f"static void {get}(ppc_cpu *c) {{ c->gpr[3] = 0x{addr:X}; c->pc = c->lr; }}\n")
            out.append(f"static void {set_}(ppc_cpu *c) {{ ppc_copy(0x{addr:X}, c->gpr[3], {ti.size}); c->pc = c->lr; }}\n")
        else:
            continue
        table.append((f"LMGet{name}", get))
        table.append((f"LMSet{name}", set_))
    return out, table


def gen_ppc(impl, sigs):
    out = [HEADER, "#include <stdbool.h>\n#include <stdint.h>\n#include <string.h>\n\n",
           '#include "ppc.h"\n#include "ppc_bridge.h"\n#include "tb_protos_gen.h"\n\n']
    table = []
    for fn in functions:
        name = fn["name"]
        if name not in impl or name not in sigs:
            continue
        sig = sigs[name]
        variants = list(fn.get("variants") or [])
        # PB calls with an async trap bit: InterfaceLib has PBxxxSync and PBxxxAsync.
        if not variants and any(c[0] == "reg" and c[1] == "TrapBit<0x400>" for _, c in sig["args"]) \
                and name.startswith("PB"):
            variants = [name, name + "Sync", name + "Async"]
        names = [None] if not variants else variants
        has_bits = any(c[0] == "reg" and c[1].startswith("TrapBit") for _, c in sig["args"])
        if variants and name not in variants:
            names = [None] + variants
        for v in names:
            if v is None and has_bits and variants:
                v_eff = None  # the base name takes the bits as arguments
            else:
                v_eff = v
            r = gen_ppc_glue(name, fn, sig, v_eff)
            if r is None:
                continue
            cname, text = r
            export = v_eff or name
            if any(e == export for e, _ in table):
                continue
            # A Toolbox trap the program has patched goes through the trap
            # table, as InterfaceLib's glue did (HyperCard 2.4 patches
            # SelectWindow and ShowWindow to keep its card window active
            # behind its palettes).
            trap = trap_num(fn)
            if v_eff is None and not fn.get("dispatcher") and trap is not None and trap & 0x0800 \
                    and sig["conv"] == "stack":
                rp = gen_ppc_trapcall(name, fn, sig, None)
                if rp is not None:
                    pname = f"ppcpatched_{name}"
                    out.append(rp[1].replace(f"static void {rp[0]}(", f"static void {pname}(", 1))
                    text = text.replace("(ppc_cpu *c)\n{\n",
                                        f"(ppc_cpu *c)\n{{\n    if (ppc_trap_patched(0x{trap:04X})) {{\n"
                                        f"        {pname}(c);\n        return;\n    }}\n", 1)
            out.append(text)
            table.append((export, cname))
    # The rest of the traps: glue running the 68k trap.
    exported = {e for e, _ in table}
    for fn in functions:
        name = fn["name"]
        # (C-convention routines are not run as 68k traps from PowerPC: only
        # the implemented ones, called directly above, are exported.)
        if name not in sigs or sigs[name]["conv"] == "c" or (trap_num(fn) is None and not fn.get("dispatcher")):
            continue
        sig = sigs[name]
        variants = list(fn.get("variants") or [])
        if not variants and any(c[0] == "reg" and c[1] == "TrapBit<0x400>" for _, c in sig["args"]) \
                and name.startswith("PB"):
            variants = [name, name + "Sync", name + "Async"]
        names = variants if variants else [None]
        if variants and name not in variants:
            names = [None] + variants
        for v in names:
            export = v or name
            if export in exported:
                continue
            r = gen_ppc_trapcall(name, fn, sig, v)
            if r is None:
                continue
            cname, text = r
            out.append(text)
            table.append((export, cname))
            exported.add(export)
    lm_out, lm_table = gen_ppc_lowmem()
    out.extend(lm_out)
    for export, cname in lm_table:
        if export not in exported:
            table.append((export, cname))
            exported.add(export)
    table.sort()
    out.append("const ppc_export ppc_exports[] = {\n")
    for export, cname in table:
        out.append(f'    {{"{export}", {cname}}},\n')
    out.append("};\nconst unsigned ppc_export_count = sizeof ppc_exports / sizeof ppc_exports[0];\n")
    write(os.path.join(OUT_TOOLBOX, "ppc_glue_gen.c"), "".join(out))
    return len(table)


def gen_traps():
    impl = implemented_names()
    os_names = {}
    tb_names = {}
    sigs = {}          # function name -> sig
    errors = []
    by_trap = {}       # trapword -> function (non-dispatched)
    by_disp = {}       # dispatcher name -> [(selector, fn)]

    for fn in functions:
        name = fn["name"]
        try:
            sigs[name] = signature(fn)
            d = dispatchers.get(fn.get("dispatcher") or "")
            if d and d.get("convention") == "C":
                sigs[name].update(conv="c", retbytes=0)
        except (KeyError, ValueError) as e:
            errors.append((name, str(e)))
        if fn.get("dispatcher"):
            by_disp.setdefault(fn["dispatcher"], []).append((fn.get("selector"), fn))
            continue
        t = trap_num(fn)
        if t is None:
            continue
        by_trap.setdefault(t, fn)

    def note(t, name):
        if t & 0x0800:
            tb_names.setdefault(t & 0x3FF, name)
        else:
            os_names.setdefault(t & 0xFF, name)

    for t, fn in by_trap.items():
        note(t, fn["name"])
    for d in dispatchers.values():
        note(trap_num(d), d["name"])

    protos = [HEADER, "#ifndef TB_PROTOS_GEN_H\n#define TB_PROTOS_GEN_H\n\n",
              "#include <stdbool.h>\n#include <stdint.h>\n#include \"mem.h\"\n\n"]
    glue = []
    # Shared-library calls (Navigation Services') have no 68k form to glue.
    library_only = {fn["name"] for fn in functions
                    if (fn.get("cfm") or fn.get("inline")) and trap_num(fn) is None and not fn.get("dispatcher")}
    for name in sorted(impl):
        if name not in sigs:
            continue
        sig = sigs[name]
        protos.append(f"{c_return(sig)} tb_{name}({', '.join(c_params(sig)) or 'void'});\n")
        if name not in library_only:
            glue.append(gen_glue(name, sig))
    protos.append("\n#endif\n")

    c = [HEADER, '#include "trap.h"\n#include "tb_protos_gen.h"\n#include "lowmem_gen.h"\n\n']
    c.append("const char *const os_trap_names[256] = {\n")
    for i in range(256):
        if i in os_names:
            c.append(f'    [0x{i:02X}] = "{os_names[i]}",\n')
    c.append("};\n\nconst char *const tb_trap_names[1024] = {\n")
    for i in range(1024):
        if i in tb_names:
            c.append(f'    [0x{i:03X}] = "{tb_names[i]}",\n')
    c.append("};\n\n")
    c.extend(glue)

    # Signatures of every undispatched trap (for census stubs), and glue entries.
    c.append("const trap_sig trap_sigs[] = {\n")
    for t in sorted(by_trap):
        fn = by_trap[t]
        sig = sigs.get(fn["name"])
        if sig is None:
            continue
        g = f"glue_{fn['name']}" if fn["name"] in impl else "0"
        conv = "CONV_STACK" if sig["conv"] == "stack" else "CONV_REG"
        c.append(f'    {{0x{t:04X}, -1, "{fn["name"]}", {conv}, {sig["argbytes"]}, {sig["retbytes"]}, {g}}},\n')
    c.append("};\nconst unsigned trap_sig_count = sizeof trap_sigs / sizeof trap_sigs[0];\n\n")

    c.append("const dispatch_sig dispatch_sigs[] = {\n")
    for dname in sorted(by_disp):
        d = dispatchers.get(dname)
        if d is None:
            continue
        t = trap_num(d)
        for sel, fn in sorted(by_disp[dname], key=lambda x: (x[0] is None, x[0] or 0)):
            sig = sigs.get(fn["name"])
            if sig is None or sel is None:
                continue
            sel = int(sel, 0) if isinstance(sel, str) else int(sel)
            g = f"glue_{fn['name']}" if fn["name"] in impl else "0"
            conv = "CONV_STACK" if sig["conv"] == "stack" else "CONV_REG"
            c.append(f'    {{0x{t:04X}, (int32_t)0x{sel & 0xFFFFFFFF:X}u, "{fn["name"]}", {conv}, {sig["argbytes"]}, {sig["retbytes"]}, {g}}},\n')
    c.append("};\nconst unsigned dispatch_sig_count = sizeof dispatch_sigs / sizeof dispatch_sigs[0];\n\n")

    c.append("const dispatcher_info dispatchers[] = {\n")
    for dname in sorted(dispatchers):
        d = dispatchers[dname]
        c.append(f'    {{0x{trap_num(d):04X}, "{dname}", "{d["selector-location"]}"}},\n')
    c.append("};\nconst unsigned dispatcher_count = sizeof dispatchers / sizeof dispatchers[0];\n")

    write(os.path.join(OUT_TOOLBOX, "include", "tb_protos_gen.h"), "".join(protos))
    write(os.path.join(OUT_TOOLBOX, "traps_gen.c"), "".join(c))
    n_ppc = gen_ppc(impl, sigs)
    print(f"  PowerPC exports: {n_ppc}")
    missing = sorted(n for n in impl if n not in sigs)
    for n in missing:
        print(f"  tb_{n}: no definition with a usable signature", file=sys.stderr)
    return len(by_trap), len(dispatchers), len(impl), errors


def write(path, text):
    old = None
    if os.path.exists(path):
        with open(path) as f:
            old = f.read()
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def main():
    load()
    if len(sys.argv) > 2 and sys.argv[1] == "--proto":
        # Print the C prototype the generator expects for each named routine.
        want = set(sys.argv[2:])
        for fn in functions:
            if fn["name"] in want:
                try:
                    sig = signature(fn)
                except (KeyError, ValueError) as e:
                    print(f"/* {fn['name']}: {e} */")
                    continue
                where = fn.get("dispatcher") or f"trap 0x{trap_num(fn) or 0:04X}"
                print(f"{c_return(sig)} tb_{fn['name']}({', '.join(c_params(sig)) or 'void'}); /* {where}, {sig['conv']} */")
        return
    n_lm = gen_lowmem()
    n_st, n_bad, n_mis = gen_structs()
    n_tr, n_disp, n_impl, errs = gen_traps()
    print(f"lowmem: {n_lm}  structs: {n_st} ({n_bad} unresolved, {n_mis} size overrides)  "
          f"traps: {n_tr}  dispatchers: {n_disp}  implemented: {n_impl}  "
          f"unusable signatures: {len(errs)}")


if __name__ == "__main__":
    main()
