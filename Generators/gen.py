#!/usr/bin/env python3
"""Generate C sources from the Multiversal interface definitions.

Run from the repository root:

    uv run --with pyyaml python Generators/gen.py

Outputs (all committed, so a normal build never needs Python):

    Sources/CCore/include/lowmem_gen.h      low-memory global addresses
    Sources/CCore/lowmem_gen.c              low-memory name table
    Sources/CCore/include/structs_gen.h     guest struct offsets, sizes, accessors
    Sources/Toolbox/include/tb_protos_gen.h prototypes for implemented tb_* routines
    Sources/Toolbox/traps_gen.c             trap names, signatures, generated glue

A Toolbox routine is "implemented" when some Sources/Toolbox/*.c file defines a
function named tb_<Name>.  Its C signature is derived from the definition, so a
mismatch between the definition and the implementation is a compile error.
"""

import glob
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DEFS = os.path.join(ROOT, "Defs", "multiversal", "defs")
OUT_CCORE = os.path.join(ROOT, "Sources", "CCore")
OUT_TOOLBOX = os.path.join(ROOT, "Sources", "Toolbox")

HEADER = "/* Generated by Generators/gen.py from Defs/multiversal. Do not edit. */\n"

# --------------------------------------------------------------------------
# Loading

typedefs = {}
structs = {}      # name -> dict(kind='struct'|'union', members=[...], size=?)
commons = {}
funptrs = set()
lowmems = []
functions = []
dispatchers = {}
enum_types = set()
constants = {}

BASE = {
    "int8_t": (1, True), "uint8_t": (1, False), "char": (1, True),
    "unsigned char": (1, False), "signed char": (1, True),
    "int16_t": (2, True), "uint16_t": (2, False), "short": (2, True),
    "unsigned short": (2, False),
    "int32_t": (4, True), "uint32_t": (4, False), "long": (4, True),
    "unsigned long": (4, False), "int": (4, True), "unsigned": (4, False),
    "unsigned int": (4, False),
    "bool": (1, False), "void": (0, False),
    "int64_t": (8, True), "uint64_t": (8, False),
    "float": (4, True), "double": (8, True),
}


def load():
    for path in sorted(glob.glob(os.path.join(DEFS, "*.yaml"))):
        with open(path) as f:
            items = yaml.safe_load(f) or []
        for item in items:
            for kind, v in item.items():
                if not isinstance(v, dict):
                    continue
                if kind == "typedef":
                    typedefs[v["name"]] = v["type"]
                elif kind in ("struct", "union"):
                    # A struct may appear twice: once with members, once with
                    # only its declared size.  Merge the two.
                    s = structs.setdefault(v["name"], dict(kind=kind, members=[], size=None))
                    if v.get("members"):
                        s["members"] = v["members"]
                        s["kind"] = kind
                    if v.get("size") is not None:
                        s["size"] = v["size"]
                elif kind == "common":
                    commons[v["name"]] = v.get("members") or []
                elif kind == "funptr":
                    funptrs.add(v["name"])
                elif kind == "lowmem":
                    lowmems.append(v)
                elif kind == "function":
                    functions.append(v)
                elif kind == "dispatcher":
                    dispatchers[v["name"]] = v
                elif kind == "enum":
                    if v.get("name"):
                        enum_types.add(v["name"])
                    for ev in v.get("values") or []:
                        if isinstance(ev, dict) and "value" in ev:
                            constants[ev["name"]] = ev["value"]


# --------------------------------------------------------------------------
# Type layout (mac68k alignment: 1-byte types byte-aligned, everything else
# word-aligned, aggregate sizes padded to even)

class TypeInfo:
    def __init__(self, size, align, signed=False, scalar=True, ptr=False, struct=None):
        self.size, self.align, self.signed = size, align, signed
        self.scalar, self.ptr, self.struct = scalar, ptr, struct


def clean(t):
    t = t.strip()
    t = re.sub(r"\bconst\b", "", t)
    t = re.sub(r"\bvolatile\b", "", t)
    t = re.sub(r"\bstruct\b", "", t)
    return " ".join(t.split())


layout_cache = {}


def type_info(t, depth=0):
    if depth > 40:
        raise ValueError("typedef loop at " + t)
    t = clean(t)
    m = re.match(r"^(.*)\[(\w+)\]$", t)
    if m:
        elem = type_info(m.group(1), depth + 1)
        n = constants.get(m.group(2), m.group(2))
        n = int(n, 0) if isinstance(n, str) else int(n)
        return TypeInfo(elem.size * n, elem.align, scalar=False)
    if t.endswith("*") or t in funptrs or t.endswith("UPP") or t == "ProcPtr":
        return TypeInfo(4, 2, ptr=True)
    if t in BASE:
        size, signed = BASE[t]
        return TypeInfo(size, 1 if size <= 1 else 2, signed)
    if t in typedefs:
        return type_info(typedefs[t], depth + 1)
    if t in structs:
        size, align = struct_layout(t)[1:]
        return TypeInfo(size, align, scalar=False, struct=t)
    if t in enum_types:
        return TypeInfo(2, 2, True)
    raise KeyError(t)


def member_list(members):
    out = []
    for m in members:
        if "common" in m:
            out.extend(member_list(commons[m["common"]]))
        else:
            out.append(m)
    return out


def struct_layout(name):
    """Return (fields, size, align); fields = [(name, offset, TypeInfo)]."""
    if name in layout_cache:
        return layout_cache[name]
    s = structs[name]
    fields, size, align = layout_members(s["kind"], member_list(s["members"]))
    layout_cache[name] = (fields, size, align)
    return layout_cache[name]


def layout_members(kind, members):
    fields = []
    off = 0
    maxsize = 0
    align = 1
    for m in members:
        if "union" in m or "struct" in m:
            sub_kind = "union" if "union" in m else "struct"
            sub_fields, sub_size, sub_align = layout_members(sub_kind, member_list(m[sub_kind]))
            ti = TypeInfo(sub_size, sub_align, scalar=False)
            nested = sub_fields
        else:
            ti = type_info(m["type"])
            nested = None
        align = max(align, ti.align)
        if kind == "struct":
            if ti.align > 1 and off % 2:
                off += 1
            fields.append((m["name"], off, ti))
            if nested:
                for (n2, o2, t2) in nested:
                    fields.append((m["name"] + "_" + n2, off + o2, t2))
            off += ti.size
        else:
            fields.append((m["name"], 0, ti))
            if nested:
                for (n2, o2, t2) in nested:
                    fields.append((m["name"] + "_" + n2, o2, t2))
            maxsize = max(maxsize, ti.size)
    size = off if kind == "struct" else maxsize
    if align > 1 and size % 2:
        size += 1
    return fields, size, align


# --------------------------------------------------------------------------
# Low memory

def gen_lowmem():
    seen = set()
    rows = []
    for v in lowmems:
        name = v["name"]
        if name in seen:
            continue
        seen.add(name)
        addr = v["address"]
        if isinstance(addr, str):
            addr = int(addr, 0)
        try:
            ti = type_info(v["type"])
            size = ti.size
        except KeyError:
            size = 0
        rows.append((addr, name, size, clean(v["type"])))
    rows.sort()
    h = [HEADER, "#ifndef LOWMEM_GEN_H\n#define LOWMEM_GEN_H\n\n"]
    for addr, name, size, t in rows:
        h.append(f"#define LM_{name} 0x{addr:04X}u /* {t}, {size} bytes */\n")
    h.append("\ntypedef struct { const char *name; unsigned addr; unsigned size; } lowmem_info;\n")
    h.append("extern const lowmem_info lowmem_table[];\nextern const unsigned lowmem_count;\n")
    h.append("\n#endif\n")
    c = [HEADER, '#include "lowmem_gen.h"\n\nconst lowmem_info lowmem_table[] = {\n']
    for addr, name, size, t in rows:
        c.append(f'    {{"{name}", 0x{addr:04X}u, {size}u}},\n')
    c.append("};\nconst unsigned lowmem_count = sizeof lowmem_table / sizeof lowmem_table[0];\n")
    write(os.path.join(OUT_CCORE, "include", "lowmem_gen.h"), "".join(h))
    write(os.path.join(OUT_CCORE, "lowmem_gen.c"), "".join(c))
    return len(rows)


# --------------------------------------------------------------------------
# Structs

def c_scalar(ti):
    if ti.ptr:
        return "gaddr", "32"
    bits = {1: "8", 2: "16", 4: "32"}[ti.size]
    return ("int" if ti.signed else "uint") + bits + "_t", bits


def gen_structs():
    out = [HEADER, "#ifndef STRUCTS_GEN_H\n#define STRUCTS_GEN_H\n\n#include \"mem.h\"\n\n"]
    bad = []
    mismatched = []
    n = 0
    for name in sorted(structs):
        try:
            fields, size, align = struct_layout(name)
        except (KeyError, ValueError) as e:
            bad.append((name, str(e)))
            continue
        declared = structs[name]["size"]
        if declared is not None and declared != size:
            mismatched.append((name, declared, size))
            size = declared
        n += 1
        out.append(f"/* {name} */\n#define {name}_SIZEOF {size}u\n")
        for fname, off, ti in fields:
            out.append(f"#define {name}_{fname}_off {off}u\n")
        for fname, off, ti in fields:
            if ti.scalar and ti.size in (1, 2, 4):
                ct, bits = c_scalar(ti)
                out.append(f"static inline {ct} {name}_{fname}(gaddr p) {{ return ({ct})rd{bits}(p + {off}u); }}\n")
                out.append(f"static inline void {name}_set_{fname}(gaddr p, {ct} v) {{ wr{bits}(p + {off}u, (uint{bits}_t)v); }}\n")
        out.append("\n")
    out.append("#endif\n")
    write(os.path.join(OUT_CCORE, "include", "structs_gen.h"), "".join(out))
    for name, err in bad:
        print(f"  struct {name}: unresolved type {err}", file=sys.stderr)
    for name, d, c in mismatched:
        print(f"  struct {name}: declared size {d}, computed {c} (using declared)", file=sys.stderr)
    return n, len(bad), len(mismatched)


# --------------------------------------------------------------------------
# Traps and glue

def implemented_names():
    names = set()
    for path in glob.glob(os.path.join(OUT_TOOLBOX, "*.c")):
        if path.endswith("_gen.c"):
            continue
        with open(path) as f:
            for line in f:
                m = re.match(r"^[A-Za-z_][\w \*]*?\btb_(\w+)\s*\(", line)
                if m:
                    names.add(m.group(1))
    return names


def trap_num(v):
    t = v.get("trap")
    if t is None:
        return None
    return int(t, 0) if isinstance(t, str) else int(t)


def arg_class(a):
    """Classify an argument: ('stack', TypeInfo) or ('reg', regspec, TypeInfo)."""
    ti = type_info(a["type"])
    if not ti.scalar and not ti.ptr:
        # Aggregates: arrays and big records travel by address; records of
        # 4 bytes or fewer travel by value.
        if ti.struct and ti.size <= 4:
            pass
        else:
            ti = TypeInfo(4, 2, ptr=True)
    if "register" in a:
        return ("reg", a["register"], ti)
    return ("stack", None, ti)


def stack_slot(ti):
    return 2 if ti.size <= 2 else 4


def ctype_for(ti):
    if ti.ptr:
        return "gaddr"
    if ti.struct and ti.size <= 4:
        return "uint32_t" if ti.size == 4 else "uint16_t"
    return {1: "uint8_t" if not ti.signed else "int8_t",
            2: "uint16_t" if not ti.signed else "int16_t",
            4: "uint32_t" if not ti.signed else "int32_t"}[ti.size]


def signature(fn):
    """Analyse a function definition. Returns dict or raises."""
    args = []
    regs = False
    for i, a in enumerate(fn.get("args") or []):
        cls = arg_class(a)
        if cls[0] == "reg":
            regs = True
        args.append((a.get("name") or f"arg{i}", cls))
    ret = fn.get("return")
    rti = None
    if ret and clean(ret) != "void":
        rti = type_info(ret)
        if not rti.scalar and not rti.ptr:
            if rti.struct and rti.size <= 4:
                pass
            else:
                raise ValueError("aggregate return")
    retreg = fn.get("returnreg")
    conv = "reg" if (regs or retreg) else "stack"
    if conv == "reg" and any(c[0] == "stack" for _, c in args):
        raise ValueError("mixed register/stack arguments")
    argbytes = sum(stack_slot(c[2]) for _, c in args if c[0] == "stack")
    retbytes = 0 if (rti is None or conv == "reg") else stack_slot(rti)
    return dict(conv=conv, args=args, rti=rti, retreg=retreg,
                argbytes=argbytes, retbytes=retbytes,
                memerr="ReturnMemErr<D0>" in str(fn.get("executor_extras", "")))


REGS = {"D0": "c->d[0]", "D1": "c->d[1]", "D2": "c->d[2]", "A0": "c->a[0]",
        "A1": "c->a[1]", "A2": "c->a[2]"}


def c_params(sig):
    params = []
    for name, cls in sig["args"]:
        kind, reg, ti = cls
        if kind == "reg" and reg.startswith("TrapBit"):
            params.append(f"bool {name}")
        elif kind == "reg" and (reg.startswith("Out<") or reg.startswith("InOut<")):
            params.append(f"uint32_t *{name}")
        else:
            params.append(f"{ctype_for(ti)} {name}")
    return params


def c_return(sig):
    if sig["rti"] is None:
        return "void"
    if sig["retreg"] == "D0Minus1Boolean":
        return "bool"
    return ctype_for(sig["rti"])


TRAPBITS = {"SYSBIT": "0x400", "CLRBIT": "0x200"}


def gen_glue(name, sig):
    """Glue reading 68k arguments, calling tb_<name>, storing the result."""
    lines = [f"static void glue_{name}(cpu68k *c, uint16_t trapword)\n{{\n",
             "    (void)trapword;\n"]
    call_args = []
    if sig["conv"] == "stack":
        lines.append("    uint32_t ret = cpu_pop32(c);\n")
        # Pascal pushes left to right, so the last argument is on top.
        for name_, cls in reversed(sig["args"]):
            ti = cls[2]
            ct = ctype_for(ti)
            if stack_slot(ti) == 4:
                lines.append(f"    {ct} a_{name_} = ({ct})cpu_pop32(c);\n")
            elif ti.size == 1:
                lines.append(f"    {ct} a_{name_} = ({ct})(cpu_pop16(c) >> 8);\n")
            else:
                lines.append(f"    {ct} a_{name_} = ({ct})cpu_pop16(c);\n")
        call_args = ["a_" + n for n, _ in sig["args"]]
        rt = c_return(sig)
        call = f"tb_{name}({', '.join(call_args)})"
        if rt == "void":
            lines.append(f"    {call};\n")
        else:
            lines.append(f"    {rt} r = {call};\n")
            ti = sig["rti"]
            if ti.size == 1:
                lines.append("    wr16(c->a[7], (uint16_t)((uint8_t)r << 8));\n")
            elif stack_slot(ti) == 2:
                lines.append("    wr16(c->a[7], (uint16_t)r);\n")
            else:
                lines.append("    wr32(c->a[7], (uint32_t)r);\n")
        lines.append("    cpu_push32(c, ret);\n")
    else:
        outs = []
        for name_, cls in sig["args"]:
            _, reg, ti = cls
            ct = ctype_for(ti)
            if reg.startswith("TrapBit"):
                bit = reg[len("TrapBit<"):-1]
                bit = TRAPBITS.get(bit, bit)
                lines.append(f"    bool a_{name_} = (trapword & {bit}) != 0;\n")
                call_args.append("a_" + name_)
            elif reg.startswith("Out<") or reg.startswith("InOut<"):
                r = reg[reg.index("<") + 1:-1]
                init = REGS[r] if reg.startswith("InOut") else "0"
                lines.append(f"    uint32_t a_{name_} = {init};\n")
                call_args.append("&a_" + name_)
                outs.append((r, "a_" + name_))
            elif reg == "D0LowWord":
                lines.append(f"    {ct} a_{name_} = ({ct})(c->d[0] & 0xFFFF);\n")
                call_args.append("a_" + name_)
            elif reg == "D0HighWord":
                lines.append(f"    {ct} a_{name_} = ({ct})(c->d[0] >> 16);\n")
                call_args.append("a_" + name_)
            else:
                lines.append(f"    {ct} a_{name_} = ({ct}){REGS[reg]};\n")
                call_args.append("a_" + name_)
        rt = c_return(sig)
        call = f"tb_{name}({', '.join(call_args)})"
        if rt == "void":
            lines.append(f"    {call};\n")
        else:
            lines.append(f"    {rt} r = {call};\n")
        for r, n_ in outs:
            lines.append(f"    {REGS[r]} = {n_};\n")
        rr = sig["retreg"]
        if rt != "void":
            if rr == "D0Minus1Boolean":
                lines.append("    c->d[0] = r ? 0 : 0xFFFFFFFFu;\n")
            elif rr in REGS:
                if sig["rti"].size == 2 and sig["rti"].signed:
                    lines.append(f"    {REGS[rr]} = (uint32_t)(int32_t)(int16_t)r;\n")
                else:
                    lines.append(f"    {REGS[rr]} = (uint32_t)r;\n")
            else:
                lines.append(f"    c->d[0] = (uint32_t)r;\n")
        if sig["memerr"]:
            lines.append("    c->d[0] = (uint32_t)(int32_t)(int16_t)rd16(LM_MemErr);\n")
    lines.append("}\n\n")
    return "".join(lines)


def gen_traps():
    impl = implemented_names()
    os_names = {}
    tb_names = {}
    sigs = {}          # function name -> sig
    errors = []
    by_trap = {}       # trapword -> function (non-dispatched)
    by_disp = {}       # dispatcher name -> [(selector, fn)]

    for fn in functions:
        name = fn["name"]
        try:
            sigs[name] = signature(fn)
        except (KeyError, ValueError) as e:
            errors.append((name, str(e)))
        if fn.get("dispatcher"):
            by_disp.setdefault(fn["dispatcher"], []).append((fn.get("selector"), fn))
            continue
        t = trap_num(fn)
        if t is None:
            continue
        by_trap.setdefault(t, fn)

    def note(t, name):
        if t & 0x0800:
            tb_names.setdefault(t & 0x3FF, name)
        else:
            os_names.setdefault(t & 0xFF, name)

    for t, fn in by_trap.items():
        note(t, fn["name"])
    for d in dispatchers.values():
        note(trap_num(d), d["name"])

    protos = [HEADER, "#ifndef TB_PROTOS_GEN_H\n#define TB_PROTOS_GEN_H\n\n",
              "#include <stdbool.h>\n#include <stdint.h>\n#include \"mem.h\"\n\n"]
    glue = []
    for name in sorted(impl):
        if name not in sigs:
            continue
        sig = sigs[name]
        protos.append(f"{c_return(sig)} tb_{name}({', '.join(c_params(sig)) or 'void'});\n")
        glue.append(gen_glue(name, sig))
    protos.append("\n#endif\n")

    c = [HEADER, '#include "trap.h"\n#include "tb_protos_gen.h"\n#include "lowmem_gen.h"\n\n']
    c.append("const char *const os_trap_names[256] = {\n")
    for i in range(256):
        if i in os_names:
            c.append(f'    [0x{i:02X}] = "{os_names[i]}",\n')
    c.append("};\n\nconst char *const tb_trap_names[1024] = {\n")
    for i in range(1024):
        if i in tb_names:
            c.append(f'    [0x{i:03X}] = "{tb_names[i]}",\n')
    c.append("};\n\n")
    c.extend(glue)

    # Signatures of every undispatched trap (for census stubs), and glue entries.
    c.append("const trap_sig trap_sigs[] = {\n")
    for t in sorted(by_trap):
        fn = by_trap[t]
        sig = sigs.get(fn["name"])
        if sig is None:
            continue
        g = f"glue_{fn['name']}" if fn["name"] in impl else "0"
        conv = "CONV_STACK" if sig["conv"] == "stack" else "CONV_REG"
        c.append(f'    {{0x{t:04X}, -1, "{fn["name"]}", {conv}, {sig["argbytes"]}, {sig["retbytes"]}, {g}}},\n')
    c.append("};\nconst unsigned trap_sig_count = sizeof trap_sigs / sizeof trap_sigs[0];\n\n")

    c.append("const dispatch_sig dispatch_sigs[] = {\n")
    for dname in sorted(by_disp):
        d = dispatchers.get(dname)
        if d is None:
            continue
        t = trap_num(d)
        for sel, fn in sorted(by_disp[dname], key=lambda x: (x[0] is None, x[0] or 0)):
            sig = sigs.get(fn["name"])
            if sig is None or sel is None:
                continue
            sel = int(sel, 0) if isinstance(sel, str) else int(sel)
            g = f"glue_{fn['name']}" if fn["name"] in impl else "0"
            conv = "CONV_STACK" if sig["conv"] == "stack" else "CONV_REG"
            c.append(f'    {{0x{t:04X}, (int32_t)0x{sel & 0xFFFFFFFF:X}u, "{fn["name"]}", {conv}, {sig["argbytes"]}, {sig["retbytes"]}, {g}}},\n')
    c.append("};\nconst unsigned dispatch_sig_count = sizeof dispatch_sigs / sizeof dispatch_sigs[0];\n\n")

    c.append("const dispatcher_info dispatchers[] = {\n")
    for dname in sorted(dispatchers):
        d = dispatchers[dname]
        c.append(f'    {{0x{trap_num(d):04X}, "{dname}", "{d["selector-location"]}"}},\n')
    c.append("};\nconst unsigned dispatcher_count = sizeof dispatchers / sizeof dispatchers[0];\n")

    write(os.path.join(OUT_TOOLBOX, "include", "tb_protos_gen.h"), "".join(protos))
    write(os.path.join(OUT_TOOLBOX, "traps_gen.c"), "".join(c))
    missing = sorted(n for n in impl if n not in sigs)
    for n in missing:
        print(f"  tb_{n}: no definition with a usable signature", file=sys.stderr)
    return len(by_trap), len(dispatchers), len(impl), errors


def write(path, text):
    old = None
    if os.path.exists(path):
        with open(path) as f:
            old = f.read()
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def main():
    load()
    if len(sys.argv) > 2 and sys.argv[1] == "--proto":
        # Print the C prototype the generator expects for each named routine.
        want = set(sys.argv[2:])
        for fn in functions:
            if fn["name"] in want:
                try:
                    sig = signature(fn)
                except (KeyError, ValueError) as e:
                    print(f"/* {fn['name']}: {e} */")
                    continue
                where = fn.get("dispatcher") or f"trap 0x{trap_num(fn) or 0:04X}"
                print(f"{c_return(sig)} tb_{fn['name']}({', '.join(c_params(sig)) or 'void'}); /* {where}, {sig['conv']} */")
        return
    n_lm = gen_lowmem()
    n_st, n_bad, n_mis = gen_structs()
    n_tr, n_disp, n_impl, errs = gen_traps()
    print(f"lowmem: {n_lm}  structs: {n_st} ({n_bad} unresolved, {n_mis} size overrides)  "
          f"traps: {n_tr}  dispatchers: {n_disp}  implemented: {n_impl}  "
          f"unusable signatures: {len(errs)}")


if __name__ == "__main__":
    main()
